def stamp(t):
    return f'{int(t)//60:02}:{t%60:06.3f}'.rstrip('0').rstrip('.')

def anchor(t):
    match = next((l for l in lines if abs(l['start']-t)<0.001),None)
    if match:
        return {'kind':'lyric_line_start','line':match['i'],'offset':0,'verified':'source_LRC_only'}
    prev = [l for l in lines if l['start'] <= t]
    if not prev:
        return {'kind':'audio_start','offset':t}
    return {'kind':'lyric_line_offset','line':prev[-1]['i'], 'offset':round(t-prev[-1]['start'],3),'verified':False}

